@app.route('/generate-test', methods=['POST'])
def generate_test():
    data = request.json

    subject = data.get('subject')
    topic = data.get('topic')
    difficulty = data.get('difficulty', 'medium')
    education_level = data.get('educationLevel', 'school')
    count = data.get('count', 5)
    answer_count = data.get('answer_count', 5)

    correct_answer_count = {5: 1, 6: 2, 7: 3}.get(answer_count, 1)

    prompt_key = f"{education_level}-{difficulty}"
    base_prompt = prompt_templates.get(prompt_key, prompt_templates['school-medium'])

    full_prompt = f"""
{base_prompt}

Сгенерируй {count} тестовых вопросов по теме: \"{topic}\" по предмету: \"{subject}\".
В каждом вопросе должно быть РОВНО {answer_count} вариантов ответа, из которых РОВНО {correct_answer_count} — правильные.
Верни результат строго в JSON формате:
[
  {{
    "question": "...",
    "options": ["..."],
    "correct_answers": ["..."]
  }}
]
    """

    try:
        response = client.chat.completions.create(
            model="gpt-3.5-turbo",
            messages=[
                {"role": "system", "content": "Ты — эксперт по образованию, создающий безошибочные тесты. Проверяй логичность, точность формулировок и структуру. Отвечай строго в JSON формате."},
                {"role": "user", "content": full_prompt}
            ],
            temperature=0.7
        )
        result = response.choices[0].message.content
        return jsonify({"result": result})
    except Exception as e:
        return jsonify({"error": str(e)}), 500

@app.route('/')
def home():
    return "✅ Сервер работает. Используй POST-запрос на /generate-test"

